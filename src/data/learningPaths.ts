export function getDirection(id: string): LearningDirection | undefined {
  return DIRECTIONS.find((direction) => direction.id === id)
}

export function getLevelLabel(id: LevelId): string {
  return LEVELS.find((level) => level.id === id)?.label ?? '有一点基础'
}
